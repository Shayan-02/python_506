# data types

# int
a = -10
print("a =>", a, "\ntype :", type(a), "\n---------")

# float
b = 16.73
print("b =>", b, "\ntype :", type(b), "\n---------")

# str
c = "salam"
d = 'chetori'
e = ''

print("c => ", c, "\ntype :", type(c), "\n---------")
print("d => ", d, "\ntype :", type(d), "\n---------")
print("e => ", e, "\ntype :", type(e), "\n---------")

# bool
f = False
h = True
g = not f
i = not h

print("f => ", f, "\ntype :", type(f), "\n---------")
print("h => ", h, "\ntype :", type(h), "\n---------")
print("g => ", g, "\ntype :", type(g), "\n---------")
print("i => ", i, "\ntype :", type(i), "\n---------")
